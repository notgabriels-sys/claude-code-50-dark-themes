#!/usr/bin/swift

import CoreGraphics
import Foundation
import ImageIO
import UniformTypeIdentifiers

enum FixtureError: Error {
    case missingDestination
    case imageCreationFailed
    case imageDestinationFailed
    case imageWriteFailed
}

guard CommandLine.arguments.count == 2 else {
    throw FixtureError.missingDestination
}

let root = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
let fileManager = FileManager.default
try fileManager.createDirectory(at: root.appendingPathComponent("Masters", isDirectory: true), withIntermediateDirectories: true)
try fileManager.createDirectory(at: root.appendingPathComponent("Artwork", isDirectory: true), withIntermediateDirectories: true)
try fileManager.createDirectory(at: root.appendingPathComponent("Credits", isDirectory: true), withIntermediateDirectories: true)

func appendUInt16LE(_ value: UInt16, to data: inout Data) {
    data.append(UInt8(truncatingIfNeeded: value))
    data.append(UInt8(truncatingIfNeeded: value >> 8))
}

func appendUInt32LE(_ value: UInt32, to data: inout Data) {
    data.append(UInt8(truncatingIfNeeded: value))
    data.append(UInt8(truncatingIfNeeded: value >> 8))
    data.append(UInt8(truncatingIfNeeded: value >> 16))
    data.append(UInt8(truncatingIfNeeded: value >> 24))
}

func makeStereoPCM24WAV(sampleRate: Int = 48_000, seconds: Int = 1) -> Data {
    let channels = 2
    let bitsPerSample = 24
    let bytesPerSample = bitsPerSample / 8
    let frameCount = sampleRate * seconds
    let blockAlign = channels * bytesPerSample
    let payloadSize = frameCount * blockAlign

    var data = Data()
    data.append(Data("RIFF".utf8))
    appendUInt32LE(UInt32(36 + payloadSize), to: &data)
    data.append(Data("WAVE".utf8))
    data.append(Data("fmt ".utf8))
    appendUInt32LE(16, to: &data)
    appendUInt16LE(1, to: &data)
    appendUInt16LE(UInt16(channels), to: &data)
    appendUInt32LE(UInt32(sampleRate), to: &data)
    appendUInt32LE(UInt32(sampleRate * blockAlign), to: &data)
    appendUInt16LE(UInt16(blockAlign), to: &data)
    appendUInt16LE(UInt16(bitsPerSample), to: &data)
    data.append(Data("data".utf8))
    appendUInt32LE(UInt32(payloadSize), to: &data)

    let amplitude = Double(0x7F_FFFF) * 0.1
    for frame in 0..<frameCount {
        let value = Int32((sin(2.0 * .pi * 440.0 * Double(frame) / Double(sampleRate)) * amplitude).rounded())
        for _ in 0..<channels {
            data.append(UInt8(truncatingIfNeeded: value))
            data.append(UInt8(truncatingIfNeeded: value >> 8))
            data.append(UInt8(truncatingIfNeeded: value >> 16))
        }
    }
    return data
}

let audioURL = root.appendingPathComponent("Masters/Main Master.wav")
try makeStereoPCM24WAV().write(to: audioURL, options: .atomic)

let width = 3_000
let height = 3_000
let colorSpace = CGColorSpaceCreateDeviceRGB()
guard let context = CGContext(
    data: nil,
    width: width,
    height: height,
    bitsPerComponent: 8,
    bytesPerRow: width * 4,
    space: colorSpace,
    bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue
) else {
    throw FixtureError.imageCreationFailed
}
context.setFillColor(red: 0.10, green: 0.09, blue: 0.08, alpha: 1.0)
context.fill(CGRect(x: 0, y: 0, width: width, height: height))
guard let image = context.makeImage() else {
    throw FixtureError.imageCreationFailed
}

let artworkURL = root.appendingPathComponent("Artwork/Cover.png")
guard let destination = CGImageDestinationCreateWithURL(
    artworkURL as CFURL,
    UTType.png.identifier as CFString,
    1,
    nil
) else {
    throw FixtureError.imageDestinationFailed
}
CGImageDestinationAddImage(destination, image, nil)
guard CGImageDestinationFinalize(destination) else {
    throw FixtureError.imageWriteFailed
}

let credits = """
Artist: Generated Fixture
Title: Audio Delivery Preflight Validation
Purpose: Original non-commercial test data generated by this repository.
"""
try Data((credits + "\n").utf8).write(to: root.appendingPathComponent("Credits/credits.md"), options: .atomic)
