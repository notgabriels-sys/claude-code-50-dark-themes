package preflight_test

import (
	"encoding/base64"
	"path/filepath"
	"testing"

	"github.com/gabrielgarciaalonso/audio-delivery-preflight-cli/preflight"
)

// A future regression that accepts a parseable header as a readable payload must
// fail this test. Required-role code consumes this positive evidence.
func TestTruncatedMediaNeverClaimsPositiveReadability(t *testing.T) {
	cases := []struct {
		name string
		file string
		body []byte
	}{
		{"WAV data header only", "main.wav", wavPCM()[:44]},
		{"AIFF common chunk only", "main.aiff", aiffPCM()},
		{"FLAC streaminfo only", "main.flac", flacStreamInfo()},
		{"FLAC frame marker only", "main.flac", append(flacStreamInfo(), 0xff, 0xf8)},
		{"FLAC truncated frame header", "main.flac", append(flacStreamInfo(), 0xff, 0xf8, 0x64)},
		{"FLAC truncated subframe payload", "main.flac", validFLAC(t)[:len(validFLAC(t))-2]},
		{"PNG signature and IHDR only", "cover.png", tinyPNG()[:33]},
		{"JPEG header only", "cover.jpg", jpegConfig(t)[:20]},
		{"GIF logical screen only", "cover.gif", gifConfig()[:13]},
		{"TIFF IFD without pixel data", "cover.tiff", tiffConfig()},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			mustWrite(t, filepath.Join(root, tc.file), tc.body)
			inventory, err := preflight.InventoryDirectory(root)
			if err != nil {
				t.Fatal(err)
			}
			media := entryByPath(t, inventory.Entries, tc.file).Media
			if media == nil || !media.Readable.Available || media.Readable.Value {
				t.Fatalf("truncated %s claimed positive readability: %#v", tc.file, media)
			}
		})
	}
}

// This is a complete FLAC reference generated by libFLAC from signed 16-bit,
// mono, 8 kHz PCM. Version 1 intentionally preserves its STREAMINFO metadata
// while withholding positive readability until it validates complete frames,
// payload, and CRC itself.
func TestCompleteFLACRetainsStreaminfoButIsNotReadableInVersionOne(t *testing.T) {
	root := t.TempDir()
	mustWrite(t, filepath.Join(root, "main.flac"), validFLAC(t))
	inventory, err := preflight.InventoryDirectory(root)
	if err != nil {
		t.Fatal(err)
	}
	media := entryByPath(t, inventory.Entries, "main.flac").Media
	if media == nil || !media.Supported || !media.SampleRate.Available || media.SampleRate.Value != 8000 {
		t.Fatalf("valid FLAC STREAMINFO evidence = %#v", media)
	}
	if !media.Readable.Available || media.Readable.Value || media.Unavailable == "" {
		t.Fatalf("valid FLAC claimed required-role readability: %#v", media)
	}
}

func validFLAC(t *testing.T) []byte {
	t.Helper()
	const encoded = "ZkxhQwAAACIAEAAQAAASAAASAfQA8AAAAAQAias6d3Tlc8uPFBKGyp+yhAAAKCAAAAByZWZlcmVuY2UgbGliRkxBQyAxLjUuMCAyMDI1MDIxMQAAAAD/+GQIAAPqAgAAAAF//4AAnMA="
	data, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		t.Fatal(err)
	}
	return data
}
