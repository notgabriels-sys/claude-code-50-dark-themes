#!/usr/bin/env node
// Writes plugins/theme-gallery/hooks/themes.ts, the data the /themes gallery
// mod draws: one entry per free theme, read from the 50 *.json files at the
// repository root and plugins/dark-themes-vol-2/themes/*.json, with the four
// colours the gallery shows and the accent family the website's finder uses.
// Nothing else is read, so only the free packs can ever reach the gallery.
//
//   node scripts/build-gallery-data.mjs           rewrites the data module
//   node scripts/build-gallery-data.mjs --check   exits 1 when it is out of date
//
// scripts/build-gallery-data.test.mjs runs the check under `node --test`, so
// the gallery cannot drift from the theme files.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { isThemeFile } from "./build-theme-index.mjs";
import { familyOf, slugOf } from "./build-theme-pages.mjs";

export const GALLERY_DATA_PATH = "plugins/theme-gallery/hooks/themes.ts";

// The free packs, in the order the gallery lists them. `dir` is relative to
// the repository root; the flagship pack's files sit at the root itself.
export const GALLERY_PACKS = [
  { id: "50-dark-themes", dir: "" },
  { id: "dark-themes-vol-2", dir: "plugins/dark-themes-vol-2/themes/" },
];

// The families in the order the website's finder offers them.
export const GALLERY_FAMILIES = ["warm", "cool", "green", "violet", "neutral"];

const HEX = /^#[0-9A-F]{6}$/;
// A single-quoted TypeScript string literal, as the rest of the module is written.
const quote = (value) => `'${String(value).replace(/[\\']/g, (c) => `\\${c}`)}'`;

function colour(file, overrides, key) {
  const value = String(overrides?.[key] ?? "").toUpperCase();
  if (!HEX.test(value)) throw new Error(`${file}: overrides.${key} is not a six-digit hex colour.`);
  return value;
}

export async function loadGalleryThemes(root) {
  const themes = [];
  for (const pack of GALLERY_PACKS) {
    const dir = new URL(pack.dir || "./", root);
    // isThemeFile, not a bare .json glob: the root also holds themes.json, the
    // published index, which is not a theme.
    const files = (await readdir(dir)).filter(isThemeFile).sort();
    if (files.length === 0) throw new Error(`No theme files in ${pack.dir || "the repository root"}.`);
    for (const file of files) {
      const path = `${pack.dir}${file}`;
      const theme = JSON.parse(await readFile(new URL(file, dir), "utf8"));
      // Claude Code names a plugin theme by its file name, so the gallery uses
      // the same slug when it marks the theme the settings select.
      const slug = file.slice(0, -".json".length);
      if (slugOf(theme.name) !== slug) {
        throw new Error(`${path}: file name does not match the slug of "${theme.name}".`);
      }
      const accent = colour(path, theme.overrides, "claude");
      themes.push({
        pack: pack.id,
        slug,
        name: theme.name,
        family: familyOf(accent),
        accent,
        text: colour(path, theme.overrides, "text"),
        panel: colour(path, theme.overrides, "userMessageBackground"),
        accent2: colour(path, theme.overrides, "permission"),
      });
    }
  }
  return themes;
}

export function renderGalleryData(themes) {
  const rows = themes.map(
    (theme) =>
      `  { pack: '${theme.pack}', slug: '${theme.slug}', name: ${quote(theme.name)}, ` +
      `family: '${theme.family}', accent: '${theme.accent}', text: '${theme.text}', ` +
      `panel: '${theme.panel}', accent2: '${theme.accent2}' },`,
  );
  return `// Generated by scripts/build-gallery-data.mjs from the free theme files: the
// *.json files at the repository root (50 Dark Themes) and
// plugins/dark-themes-vol-2/themes/*.json (Dark Themes Vol. 2). Do not edit by
// hand: change a theme file, then run \`node scripts/build-gallery-data.mjs\`.
//
// accent is overrides.claude, text overrides.text, panel
// overrides.userMessageBackground and accent2 overrides.permission. family is
// the accent family the website's theme finder uses.

export type Pack = ${GALLERY_PACKS.map((pack) => `'${pack.id}'`).join(" | ")}
export type Family = ${GALLERY_FAMILIES.map((family) => `'${family}'`).join(" | ")}

export type GalleryTheme = {
  pack: Pack
  slug: string
  name: string
  family: Family
  accent: string
  text: string
  panel: string
  accent2: string
}

export const THEMES: readonly GalleryTheme[] = [
${rows.join("\n")}
]
`;
}

export async function buildGalleryData(root) {
  return renderGalleryData(await loadGalleryThemes(root));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = new URL("../", import.meta.url);
  const expected = await buildGalleryData(root);
  const target = new URL(GALLERY_DATA_PATH, root);
  if (process.argv.includes("--check")) {
    let actual = "";
    try {
      actual = await readFile(target, "utf8");
    } catch {
      // A missing file is out of date like any other.
    }
    if (actual !== expected) {
      console.error(`${GALLERY_DATA_PATH} is out of date with the theme files. Run node scripts/build-gallery-data.mjs.`);
      process.exit(1);
    }
    console.log(`${GALLERY_DATA_PATH} matches the theme files.`);
  } else {
    await writeFile(target, expected);
    console.log(`Wrote ${GALLERY_DATA_PATH}.`);
  }
}
